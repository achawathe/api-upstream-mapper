CASES = json.loads((Path(__file__).parents[1] / 'fixtures/context-candidates.json').read_text())


def make_spec(name, schema, samples):
    spec = ApiSpec(name, name, '1', SpecKind.OPENAPI_3, name,
                   endpoints=(Endpoint('GET', '/accounts', name, response_schema=schema),))
    return attach_responses(spec, 'GET /accounts', [(f'{name}-{i}.json', v) for i, v in enumerate(samples)])


def run_case(case, lexicon, reverse=False):
    up = make_spec('up', case['target'], case['up_samples'])
    down = make_spec('down', case['source'], case['down_samples'])
    target_nodes, source_nodes = flatten_spec(up), flatten_spec(down)
    profiler = Profiler(lexicon, Profiler.vocabulary_of(target_nodes))
    targets, sources = profiler.profile_spec(up, target_nodes), profiler.profile_spec(down, source_nodes)
    return MatchingEngine(lexicon).match(targets, sources[::-1] if reverse else sources)[0]


@pytest.mark.parametrize('case', CASES, ids=lambda c: c['id'])
@pytest.mark.parametrize('reverse', [False, True])
def test_context_selects_supported_sources_for_review_or_abstains(case, reverse, lexicon):
    mapping = run_case(case, lexicon, reverse)
    assert (mapping.chosen.source.path if mapping.chosen else None) == case['expected']
    assert mapping.status.value == ('review' if case['expected'] else 'unmapped')
    if mapping.chosen:
        assert any(e.signal == 'context_review' for e in mapping.chosen.evidence)
        assert any(e.signal == 'purpose_support' for e in mapping.chosen.evidence)


@pytest.mark.parametrize('description', [
    'Not the bank account identifier.',
    'This is never a bank account identifier.',
    'May be a persistent bank account identifier.',
    'This value could be an account identifier.',
    'Identifier not generated by the upstream service.',
    'A label, rather than a bank account identifier.',
])
def test_negated_or_conditional_text_does_not_assert_a_purpose(lexicon, description):
    node = FieldNode('up', 'GET /x', 'value', 'string', description=description)
    assert field_purposes(node, lexicon.purpose_rules) == ()


def test_purpose_does_not_depend_on_field_spelling(lexicon):
    case = next(c for c in CASES if c['id'] == 'persistent_identity_vs_request_echo')
    case = json.loads(json.dumps(case))
    case['source']['properties']['z9'] = case['source']['properties'].pop('ledgerKey')
    for sample in case['down_samples']:
        sample['z9'] = sample.pop('ledgerKey')
    assert run_case(case, lexicon).chosen.source.path == 'z9'


def test_clues_do_not_cross_array_records_or_borrow_undeclared_metadata(lexicon):
    schema = {'type': 'object', 'properties': {'rows': {'type': 'array', 'items': {'type': 'object', 'properties': {
        'value': {'type': 'string'}, 'meaning': {'type': 'string'}, 'other': {'type': 'string'},
    }}}}}
    samples = [{'rows': [{'value': 'A', 'meaning': 'Persistent bank account identifier'},
                         {'meaning': 'Request correlation identifier', 'other': 'B'}]}]
    spec = make_spec('down', schema, samples)
    nodes = {n.path: n for n in flatten_spec(spec)}
    assert [c.text for c in nodes['rows[].value'].context_clues] == ['Persistent bank account identifier']
    assert nodes['rows[].other'].context_clues == ()
    schema['properties']['rows']['items']['properties'].pop('meaning')
    assert all(n.context_clues == () for n in flatten_spec(make_spec('down', schema, samples)))


def test_conflicting_sample_purposes_are_not_a_confirmed_identity(lexicon):
    case = json.loads(json.dumps(next(c for c in CASES if c['id'] == 'sibling_context_account')))
    case['down_samples'].append({'record': {'meaning': 'Request correlation identifier', 'value': 'another'}})
    mapping = run_case(case, lexicon)
    assert mapping.chosen is None


def test_clues_are_declared_in_the_same_schema_variant():
    schema = {'oneOf': [
        {'title': 'Plain', 'type': 'object', 'properties': {'value': {'type': 'string'}}},
        {'title': 'Defined', 'type': 'object', 'properties': {
            'value': {'type': 'string'}, 'meaning': {'type': 'string'}}},
    ]}
    nodes = flatten_spec(make_spec('down', schema, [{'value': 'A', 'meaning': 'Persistent bank account identifier'}]))
    plain = next(n for n in nodes if n.variant == 'Plain')
    assert plain.context_clues == ()


def test_values_alone_do_not_prove_identifier_ownership(lexicon):
    case = json.loads(json.dumps(next(c for c in CASES if c['id'] == 'sibling_context_account')))
    case['down_samples'][0]['record'].pop('meaning')
    mapping = run_case(case, lexicon)
    assert mapping.chosen is None


def test_comparison_explains_the_selected_source_and_excluded_rival(lexicon):
    case = next(c for c in CASES if c['id'] == 'persistent_identity_vs_request_echo')
    mapping = run_case(case, lexicon)
    comparison = mapping_to_dict(mapping)['comparison']
    assert 'Confirm' in comparison['summary']
    assert any('schema:ledgerKey.description' in text for text in comparison['support'])
    rival = next(c for c in comparison['alternatives'] if c['source'] == 'down:accountId')
    assert rival['reason'].startswith('Excluded:')
    assert 'request correlation' in rival['reason']
    mapping.status = MappingStatus.MANUAL
    assert 'reviewer' in mapping_to_dict(mapping)['comparison']['summary']


@pytest.mark.parametrize('kind', ['type', 'array', 'role'])
def test_purpose_support_cannot_rescue_incompatible_candidates(lexicon, kind):
    case = json.loads(json.dumps(next(c for c in CASES if c['id'] == 'persistent_identity_vs_request_echo')))
    properties = case['source']['properties']
    definition = properties.pop('ledgerKey')
    if kind == 'type':
        definition['type'] = 'boolean'
        properties['z9'] = definition
    elif kind == 'array':
        properties['z9'] = {'type': 'array', 'items': definition}
    else:
        properties['beneficiaryLedgerKey'] = definition
    case['down_samples'] = []
    mapping = run_case(case, lexicon)
    assert mapping.status is not MappingStatus.AUTO
    for candidate in (mapping.chosen, *mapping.alternatives):
        if candidate and candidate.source.path != 'accountId':
            assert not any(e.signal == 'context_review' for e in candidate.evidence)


def test_comparison_survives_excel_export(lexicon, tmp_path):
    case = next(c for c in CASES if c['id'] == 'persistent_identity_vs_request_echo')
    mapping = run_case(case, lexicon)
    run = MappingRun(make_spec('up', case['target'], []), (), [mapping])
    workbook = load_workbook(write_excel_report(run, tmp_path / 'report.xlsx'))
    rows = list(workbook['Candidate Comparison'].values)
    text = ' '.join(str(cell) for row in rows for cell in row if cell is not None)
    assert 'schema:ledgerKey.description' in text
    assert 'request correlation' in text


@pytest.mark.parametrize(('status', 'expected'), [
    (MappingStatus.DERIVED, "schema's variant definition"),
    (MappingStatus.REJECTED, 'Rejected by a reviewer'),
])
def test_comparison_respects_non_matching_decisions(lexicon, status, expected):
    mapping = run_case(CASES[1], lexicon)
    mapping.chosen = None
    mapping.status = status
    assert expected in mapping_to_dict(mapping)['comparison']['summary']


@pytest.mark.parametrize('patterns', ['account identifier', [], [''], ['[']])
def test_invalid_purpose_patterns_are_rejected_when_loading(patterns, tmp_path):
    path = tmp_path / 'lexicon.json'
    path.write_text(json.dumps({'purpose_rules': [{'group': 'owner', 'role': 'account',
                                                 'label': 'Account identity', 'patterns': patterns}]}))
    with pytest.raises(ValueError, match='purpose rule'):
        Lexicon.load(path)
